#!/bin/bash
# One-time setup of the Wazuh SOC: private PKI (TLS between all SOC components)
# and random credentials. Idempotent: existing certificates/secrets are kept.
#
# Run from the project root, inside the CI toolbox image (it has openssl + python3):
#   docker run --rm -v "${PWD}:/r" -w /r telecom-ci:latest bash soc/setup.sh
set -euo pipefail
cd "$(dirname "$0")"

CERTS=certs
SUBJ="/C=TN/L=Tunis/O=MiniTelecom/OU=SOC"
mkdir -p "$CERTS"

if [ ! -f "$CERTS/root-ca.pem" ]; then
    echo "[soc] Creating SOC root CA"
    openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:3072 -out "$CERTS/root-ca.key" 2>/dev/null
    openssl req -x509 -new -key "$CERTS/root-ca.key" -sha256 -days 1825 \
        -subj "$SUBJ/CN=MiniTelecom SOC Root CA" -out "$CERTS/root-ca.pem"
fi

issue() {
    local name=$1 san=$2
    [ -f "$CERTS/$name.pem" ] && return 0
    echo "[soc] Issuing certificate for $name"
    # PKCS#8 keys (required by OpenSearch)
    openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$CERTS/$name-key.pem" 2>/dev/null
    openssl req -new -key "$CERTS/$name-key.pem" -subj "$SUBJ/CN=$name" -out "$CERTS/$name.csr"
    printf 'subjectAltName=%s\nkeyUsage=critical,digitalSignature,keyEncipherment\nextendedKeyUsage=serverAuth,clientAuth\n' \
        "$san" > "$CERTS/$name.ext"
    openssl x509 -req -in "$CERTS/$name.csr" -CA "$CERTS/root-ca.pem" -CAkey "$CERTS/root-ca.key" \
        -CAcreateserial -days 825 -sha256 -extfile "$CERTS/$name.ext" -out "$CERTS/$name.pem" 2>/dev/null
    rm -f "$CERTS/$name.csr" "$CERTS/$name.ext"
}

issue admin           "DNS:admin"
issue wazuh.indexer   "DNS:wazuh.indexer,DNS:telecom-wazuh-indexer,IP:172.30.0.91"
issue wazuh.manager   "DNS:wazuh.manager,DNS:telecom-wazuh-manager,IP:172.30.0.90"
issue wazuh.dashboard "DNS:wazuh.dashboard,DNS:localhost,IP:127.0.0.1,IP:172.30.0.92"

# Lab: the Wazuh containers run as non-root users and must read the mounted files
chmod 644 "$CERTS"/*.pem
chmod 600 "$CERTS/root-ca.key"

if [ ! -f secrets.env ]; then
    echo "[soc] Generating random credentials (soc/secrets.env)"
    python3 - <<'PY'
import secrets, string
def pw(n=24):
    # Wazuh API policy: upper, lower, digit and symbol
    while True:
        p = ''.join(secrets.choice(string.ascii_letters + string.digits + '.-_') for _ in range(n))
        if any(c.islower() for c in p) and any(c.isupper() for c in p) \
           and any(c.isdigit() for c in p) and any(c in '.-_' for c in p):
            return p
with open('secrets.env', 'w') as f:
    f.write('INDEXER_USERNAME=admin\nINDEXER_PASSWORD=%s\n' % pw())
    f.write('DASHBOARD_USERNAME=kibanaserver\nDASHBOARD_PASSWORD=%s\n' % pw())
    f.write('API_USERNAME=wazuh-wui\nAPI_PASSWORD=%s\n' % pw())
PY
    chmod 600 secrets.env
fi

echo "[soc] Writing indexer internal users (bcrypt hashes)"
python3 - <<'PY' 2>/dev/null
import crypt
env = dict(l.strip().split('=', 1) for l in open('secrets.env') if '=' in l)
h = lambda p: crypt.crypt(p, crypt.mksalt(crypt.METHOD_BLOWFISH))
with open('config/wazuh_indexer/internal_users.yml', 'w') as f:
    f.write('---\n# Generated by soc/setup.sh - do not edit, do not commit\n')
    f.write('_meta:\n  type: "internalusers"\n  config_version: 2\n\n')
    f.write('admin:\n  hash: "%s"\n  reserved: true\n  backend_roles:\n    - "admin"\n' % h(env['INDEXER_PASSWORD']))
    f.write('  description: "SOC administrator"\n\n')
    f.write('kibanaserver:\n  hash: "%s"\n  reserved: true\n' % h(env['DASHBOARD_PASSWORD']))
    f.write('  description: "Wazuh dashboard service account"\n')
PY
chmod 644 config/wazuh_indexer/internal_users.yml
echo "[soc] Done. Dashboard login: admin / INDEXER_PASSWORD from soc/secrets.env"
